# Имена экспериментальных фотографий,
# которые мы решили больше не использовать.
BAD_IMAGE_PATTERN = re.compile(
    r"^(fishing-\d+\.(jpg|jpeg|png|webp)|"
    r"ohotaktiv-\d+\.(jpg|jpeg|png|webp))$",
    re.IGNORECASE,
)


def parse_products(slug):
    """Преобразует текстовый список в данные товаров."""

    for line in CATALOG[slug].strip().splitlines():
        fields = [field.strip() for field in line.split("|")]

        if len(fields) != 6:
            raise ValueError(
                f"Неверная строка товара: {line}"
            )

        name, brand, price, old_price, stock, description = fields

        yield {
            "name": name,
            "brand": brand,
            "price": int(price),
            "old_price": int(old_price) if old_price else None,
            "stock": int(stock),
            "description": description,
        }


def get_or_create_category(slug):
    """Получает существующую категорию или создаёт её."""

    category = Category.query.filter_by(slug=slug).first()

    if category is not None:
        return category

    name, icon, description, _ = CATEGORIES[slug]

    category = Category(
        name=name,
        slug=slug,
        icon=icon,
        description=description,
    )

    db.session.add(category)
    db.session.flush()

    print(f"Создана категория: {name}")

    return category


def is_test_product(product):
    """Исключает специальный товар для тестирования оплаты."""
    return product.name.strip().lower() == "тест"


def clean_bad_references():
    """Убирает ссылки на неудачные экспериментальные фото."""

    changed = 0

    for product in Product.query.all():
        filename = Path(
            (product.image or "").replace("\\", "/")
        ).name

        if BAD_IMAGE_PATTERN.fullmatch(filename):
            product.image = ""
            changed += 1

    return changed


def fill_database():
    """Добавляет недостающие товары без удаления существующих."""

    total_added = 0

    for slug in CATEGORIES:

        category = get_or_create_category(slug)

        existing = Product.query.filter_by(
            category_id=category.id
        ).all()

        normal_count = sum(
            not is_test_product(product)
            for product in existing
        )

        added = 0

        for data in parse_products(slug):

            if normal_count >= 20:
                break

            # Не добавляем товар повторно.
            duplicate = Product.query.filter_by(
                name=data["name"]
            ).first()

            if duplicate is not None:
                continue

            product = Product(
                name=data["name"],
                slug=unique_slug(Product, data["name"]),
                brand=data["brand"],
                description=data["description"],
                price=data["price"],
                old_price=data["old_price"],
                stock=data["stock"],
                image="",
                is_active=True,
                category_id=category.id,
            )

            db.session.add(product)
            db.session.flush()

            added += 1
            normal_count += 1

        total_added += added

        print(
            f"{category.name}: "
            f"{normal_count} обычных товаров, "
            f"добавлено {added}"
        )

        if normal_count < 20:
            print(
                f"ВНИМАНИЕ: до 20 не хватает "
                f"{20 - normal_count} товаров."
            )

    cleaned = clean_bad_references()

    db.session.commit()

    print(f"\nВсего добавлено: {total_added}")
    print(f"Удалено ссылок на плохие фото: {cleaned}")

    create_photo_list()


def create_photo_list():
    """Создаёт CSV со списком изображений для поиска."""

    UPLOADS.mkdir(
        parents=True,
        exist_ok=True,
    )

    rows = []

    for slug, details in CATEGORIES.items():

        category = Category.query.filter_by(
            slug=slug
        ).first()

        if category is None:
            continue

        prefix = details[3]

        products = (
            Product.query
            .filter_by(category_id=category.id)
            .order_by(Product.id)
            .all()
        )

        number = 0

        for product in products:

            if is_test_product(product):
                continue

            number += 1

            filename = f"{prefix}-{number:03d}.jpg"

            rows.append({
                "category": category.name,
                "product_id": product.id,
                "product_name": product.name,
                "filename": filename,
                "current_image": product.image or "",
            })

    with PHOTO_LIST.open(
        "w",
        encoding="utf-8-sig",
        newline="",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=[
                "category",
                "product_id",
                "product_name",
                "filename",
                "current_image",
            ],
            delimiter=";",
        )

        writer.writeheader()
        writer.writerows(rows)

    print(
        f"\nСоздан список фотографий: "
        f"{PHOTO_LIST.name}"
    )

    print(f"Позиций в списке: {len(rows)}")


def sync_photos():
    """Привязывает скачанные вручную фотографии к товарам."""

    if not PHOTO_LIST.exists():
        raise RuntimeError(
            "Сначала запустите python fill_catalog.py"
        )

    updated = 0
    missing = 0

    with PHOTO_LIST.open(
        "r",
        encoding="utf-8-sig",
        newline="",
    ) as file:

        reader = csv.DictReader(
            file,
            delimiter=";",
        )

        for row in reader:

            product = db.session.get(
                Product,
                int(row["product_id"]),
            )

            if product is None:
                continue

            # Проверяем, что ID по-прежнему
            # относится к нужному товару.
            if product.name != row["product_name"]:
                print(
                    f"Пропущен изменённый товар: "
                    f"{row['product_name']}"
                )
                continue

            filename = row["filename"]
            path = UPLOADS / filename

            if path.is_file() and path.stat().st_size > 0:

                if product.image != filename:
                    product.image = filename
                    updated += 1

            else:
                missing += 1

    db.session.commit()

    print(f"Фотографий привязано: {updated}")
    print(f"Фотографий пока нет: {missing}")


def main():
    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--photos",
        action="store_true",
        help="Привязать локальные фотографии",
    )

    parser.add_argument(
        "--list",
        action="store_true",
        help="Обновить список фотографий",
    )

    args = parser.parse_args()

    app = create_app()

    with app.app_context():

        if args.photos:
            sync_photos()

        elif args.list:
            create_photo_list()

        else:
            fill_database()


if __name__ == "__main__":
    main()
